"""Renders `deploy/trino-dev` from `charts/trino`, so the two cannot disagree.

`charts/trino` and `deploy/trino-dev` are the same Trino deployment. They agreed when both
were hand-written, but nothing enforced it, and the asymmetry made that worse than it
sounds: every tier 2 test runs against the manifests, so a chart fix that was not mirrored
into them was a fix no end-to-end test exercised -- and a manifest fix not mirrored back was
a chart nobody would find broken until they installed it.

The manifests keep their job rather than being replaced by a `helm install`. Tier 2 resets
the Cluster to them between tests (#53) and CI's tier 2 job applies them with `kubectl` and
needs no Helm at all; a Helm release inside that loop would be slower and would add a
failure mode to the thing that detects failures. What they stop being is a second
hand-written source.

Textual, not a YAML round-trip, and deliberately so. The comments in these manifests carry
most of what is known about Trino's and the kubelet's behaviour -- why a mount is whole-volume
rather than subPath, why the catalog store is an emptyDir -- and `yaml.safe_load` then `dump`
would silently throw every one of them away.

What it does not render: the Secrets. `charts/trino` creates none, because they hold
configuration Apchi writes and Apchi's chart creates them (which is why Apchi is installed
first). Two of them are already generated, by `export_access_control.py` and
`export_user_mapping.py`; the remaining four are fixture scaffolding standing in for what
Apchi's chart would have created, and they stay hand-written in `01-secrets.yaml`. Rendering
them from `charts/apchi` would make the Trino fixture depend on Apchi's MongoDB values and
stamp `app.kubernetes.io/name: apchi` on them, to generate three empty Secrets and a one-line
catalog seed. Their names are checked where it counts anyway: the generated Deployments mount
them by name, so a disagreement stops Trino from starting rather than passing quietly.
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHART = ROOT / "charts" / "trino"
TARGET_DIR = ROOT / "deploy" / "trino-dev"
#: Beside the directory, never inside it: CI and the tier 2 fixture both apply the
#: directory with `kubectl apply -f`, which sweeps in every .yaml it finds and fails on one
#: that is not a manifest. Verified -- "apiVersion not set, kind not set".
VALUES = ROOT / "deploy" / "trino-dev.values.yaml"

#: The release name, which the chart derives every other name from. Apchi's own test
#: settings name these Deployments and this Service, so it is not free to change.
RELEASE = "trino"

#: Which rendered documents go in which file, in this order. Explicit rather than derived
#: from the chart's own output order, so the Deployment leads each file it is in and a
#: reviewer reads the manifests in the order they would install them.
LAYOUT: dict[str, list[tuple[str, str]]] = {
    "00-config.yaml": [("ConfigMap", "trino-config")],
    "10-coordinator.yaml": [("Deployment", "trino-coordinator"), ("Service", "trino")],
    "20-worker.yaml": [("Deployment", "trino-worker")],
}

#: Metadata that only means something inside a Helm release. These manifests are applied
#: with `kubectl`, so `managed-by: Helm` would assert something false, and `helm.sh/chart`
#: carries the chart version -- which would churn every one of these files on a version
#: bump that changed nothing about the deployment.
HELM_ONLY = ("app.kubernetes.io/managed-by:", "helm.sh/chart:")

HEADER = """# Generated by scripts/export_trino_dev.py from charts/trino. Do not edit.
#
# Edit the chart, or deploy/trino-dev.values.yaml, and regenerate. CI fails if this file
# differs from what the chart renders, so the manifests tier 2 runs against and the chart
# an Operator installs cannot drift apart.
"""


def _rendered() -> str:
    """The chart as Helm renders it, with the values the fixture needs."""
    command = ["helm", "template", RELEASE, str(CHART), "--values", str(VALUES)]
    try:
        finished = subprocess.run(command, capture_output=True, text=True, check=True)
    except FileNotFoundError:
        raise SystemExit(
            "helm is not on PATH, and these manifests are rendered from a chart. Install "
            "Helm, or leave them alone -- they are generated output and editing them is "
            "what this script exists to prevent."
        ) from None
    except subprocess.CalledProcessError as failed:
        raise SystemExit(f"helm could not render {CHART.name}:\n{failed.stderr}") from None
    return finished.stdout


def _documents(rendered: str) -> dict[tuple[str, str], str]:
    """Helm's output split into documents, keyed by kind and name.

    Keyed rather than ordered because `LAYOUT` decides the order, and identified by a line
    scan rather than by parsing: parsing would mean re-serialising, which loses the
    comments this output exists to carry.
    """
    documents: dict[tuple[str, str], str] = {}
    for chunk in rendered.split("\n---\n"):
        body = chunk.strip("\n")
        if not body:
            continue
        lines = [
            line
            for line in body.splitlines()
            # Helm's own output: a leading document marker on the first chunk, and a
            # provenance comment this script states once in its own header instead.
            if line != "---" and not line.startswith("# Source:")
        ]
        kind = next(
            (line.removeprefix("kind:").strip() for line in lines if line.startswith("kind:")), None
        )
        name = next(
            (line.removeprefix("  name:").strip() for line in lines if line.startswith("  name:")),
            None,
        )
        if kind is None or name is None:
            raise SystemExit(f"a rendered document has no kind or name:\n{body}")
        documents[(kind, name)] = "\n".join(lines).strip("\n")
    return documents


def _without_helm_only(document: str) -> str:
    """The document less the metadata that only means something under Helm.

    A line filter and nothing cleverer. The first version of this also dropped a mapping key
    whose every child had been stripped, by looking for a line ending in `:` with nothing
    indented under it -- and it silently deleted a *comment* ending in a colon, because a
    comment looks exactly like that. The comments here are the point of generating text
    rather than YAML, so the check below refuses the case instead of trying to tidy it.
    """
    kept = [line for line in document.splitlines() if not line.strip().startswith(HELM_ONLY)]
    for index, line in enumerate(kept[:-1]):
        stripped = line.strip()
        if stripped.startswith("#") or not stripped.endswith(":"):
            continue
        following = kept[index + 1]
        if len(following) - len(following.lstrip()) <= len(line) - len(line.lstrip()):
            raise SystemExit(
                f"stripping {HELM_ONLY} left {stripped!r} mapping to nothing. Whatever was "
                "added to HELM_ONLY takes the last child of a block with it, so the block "
                "has to go too -- which this deliberately will not guess at."
            )
    return "\n".join(kept)


def render() -> dict[Path, str]:
    documents = _documents(_rendered())
    unplaced = set(documents) - {key for keys in LAYOUT.values() for key in keys}
    if unplaced:
        raise SystemExit(
            "the chart renders documents this script does not know where to put: "
            f"{sorted(unplaced)}. Add them to LAYOUT -- a rendered resource silently left "
            "out of the manifests is a fixture that no longer matches the chart."
        )
    outputs: dict[Path, str] = {}
    for filename, keys in LAYOUT.items():
        missing = [key for key in keys if key not in documents]
        if missing:
            raise SystemExit(f"the chart no longer renders {missing}, which {filename} needs")
        bodies = [_without_helm_only(documents[key]) for key in keys]
        outputs[TARGET_DIR / filename] = HEADER + "---\n" + "\n---\n".join(bodies) + "\n"
    return outputs


def main() -> int:
    outputs = render()
    if "--check" in sys.argv:
        for target, expected in outputs.items():
            if not target.exists():
                print(f"{target.name} is missing; run scripts/export_trino_dev.py", file=sys.stderr)
                return 1
            if target.read_text() != expected:
                print(
                    f"{target.name} is not what charts/trino renders. Regenerate it with "
                    "scripts/export_trino_dev.py and commit the result, so the manifests "
                    "tier 2 runs against stay the chart an Operator installs.",
                    file=sys.stderr,
                )
                return 1
        return 0
    for target, content in outputs.items():
        target.write_text(content)
        print(f"wrote {target.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
