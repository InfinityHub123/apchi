export type IconName = keyof typeof PATHS;

export function Icon({
  name,
  size = 15,
  width = 1.8,
  label,
  color,
}: {
  name: IconName;
  size?: number;
  width?: number;
  label?: string;
  color?: string;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke={color ?? "currentColor"}
      strokeWidth={width}
      strokeLinecap="round"
      strokeLinejoin="round"
      {...(label === undefined
        ? { "aria-hidden": true }
        : { role: "img", "aria-label": label })}
    >
      {PATHS[name]}
    </svg>
  );
}

